def guide_request(text):
 text=text.strip()
 if text.startswith(('/', '【暂停】')):return False
 if re.search(r'(?:不要|别|不用|不想)(?:再)?(?:介绍|讲解|讲|读|看|说明)(?:一下)?(?:世界观|规则|玩法)',text):return False
 topic=bool(re.search(r'世界观|规则书|基本玩法|新手入门|入门导读|这个游戏怎么玩|这游戏怎么玩|^怎么玩[？?。！!]*$',text))
 general_rules=bool(re.search(r'(?:主要|基本|基础|入门)规则|规则(?:概述|介绍)|(?:介绍|讲讲|讲一下|讲解)(?:一下)?规则',text))
 request=bool(re.search(r'介绍|简要|概述|讲讲|讲一下|讲解|说明|读读|读一下|想读|想看|看看|入门|大概|基础|主要|是什么|怎么玩',text))
 return (topic or general_rules) and request
